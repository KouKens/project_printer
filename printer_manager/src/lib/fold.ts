/**
 * 表記ゆれを畳んで突き合わせるための鍵。
 *
 * - `NFKC` で全角英数（`ＲＩＣＯＨ`）を半角に、半角カナ（`ｷﾔﾉﾝ`）を全角に揃える
 * - `toLowerCase()` で大文字小文字を畳む（`RICOH` / `Ricoh`）
 *
 * **API 側の `makerKey`（`maint-vendors.service.ts`）と同じ畳み方にしてある。**
 * 画面と API で畳み方が違うと、画面では同じメーカーに見えるのに保守業者が
 * 引けない、といった食い違いが起きる。片方を変えるときは必ず両方を直すこと。
 *
 * **畳むのは比べるときだけで、保存する値は畳まない。** 画面が送るのは
 * 利用者が打った文字そのままで、ここは突き合わせの鍵を作るためだけに使う。
 *
 * 一覧の絞り込み（部署・型番などで探す入力欄）には使っていない。
 * あちらは部分一致で探すためのもので、同じものかどうかを決める判定ではない
 */
export function foldKey(text: string): string {
  return text.trim().normalize('NFKC').toLowerCase();
}
